package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	modulePath, err := detectModulePath()
	if err != nil {
		fail(err)
	}

	pluginsRoot := filepath.Clean("..")

	entries, err := os.ReadDir(pluginsRoot)
	if err != nil {
		fail(fmt.Errorf("read plugins root: %w", err))
	}

	imports := make([]string, 0, len(entries))
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		name := entry.Name()
		if name == "register" || strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			continue
		}

		if hasPluginEntry(filepath.Join(pluginsRoot, name)) {
			importPath := fmt.Sprintf("%s/internal/plugins/%s", modulePath, name)
			imports = append(imports, importPath)
		}
	}

	sort.Strings(imports)

	if err := writeRegister(imports); err != nil {
		fail(err)
	}
}

func detectModulePath() (string, error) {
	path := filepath.Clean(filepath.Join("..", "..", "..", "go.mod"))
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read go.mod: %w", err)
	}

	const prefix = "module "
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, prefix) {
			return strings.TrimSpace(strings.TrimPrefix(line, prefix)), nil
		}
	}

	return "", errors.New("module path not found in go.mod")
}

func hasPluginEntry(dir string) bool {
	found := false
	filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || found {
			return err
		}
		if d.IsDir() {
			// Ignore nested plugin directories; only check current level files.
			if filepath.Clean(path) != filepath.Clean(dir) {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.EqualFold(d.Name(), "plugin.go") {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	return found
}

func writeRegister(imports []string) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./generate; DO NOT EDIT.\n")
	buf.WriteString("\n")
	buf.WriteString("package register\n\n")

	if len(imports) == 0 {
		buf.WriteString("func init() {}\n")
	} else {
		buf.WriteString("import (\n")
		for _, imp := range imports {
			buf.WriteString(fmt.Sprintf("\t_ \"%s\"\n", imp))
		}
		buf.WriteString(")\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}

	outPath := filepath.Join(".", "zz_generated_register.go")
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write generated file: %w", err)
	}

	return nil
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "register: %v\n", err)
	os.Exit(1)
}
